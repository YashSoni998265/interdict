"""Canonical status values (solution.md §10.2). Use these everywhere; never invent new strings."""

from __future__ import annotations

from enum import StrEnum


class CollectionStatus(StrEnum):
    COLLECTED_COMPLETE = "COLLECTED_COMPLETE"
    COLLECTED_EMPTY = "COLLECTED_EMPTY"
    QUERY_FAILED = "QUERY_FAILED"
    STALE_EXPIRED = "STALE_EXPIRED"
    UNCOLLECTED = "UNCOLLECTED"


class InvestigationStatus(StrEnum):
    QUALIFYING_MODELED_CHAIN = "QUALIFYING_MODELED_CHAIN"
    NOT_QUALIFIED = "NOT_QUALIFIED"
    INCONCLUSIVE = "INCONCLUSIVE"


class InconclusiveReason(StrEnum):
    QUERY_FAILED = "QUERY_FAILED"
    STALE_EVIDENCE = "STALE_EVIDENCE"
    UNCOLLECTED_EVIDENCE = "UNCOLLECTED_EVIDENCE"
    UNVERIFIED_EVIDENCE = "UNVERIFIED_EVIDENCE"
    CONTRADICTORY_EVIDENCE = "CONTRADICTORY_EVIDENCE"
    INVENTORY_INCOMPLETE = "INVENTORY_INCOMPLETE"
    METHOD_DISAGREEMENT = "METHOD_DISAGREEMENT"
    REVISION_CHANGED = "REVISION_CHANGED"


class AlertTriageClass(StrEnum):
    ON_ATTACK_PATH = "ON_ATTACK_PATH"
    NOT_ON_ATTACK_PATH = "NOT_ON_ATTACK_PATH"
    NOT_ACTIONABLE = "NOT_ACTIONABLE"
    TRIAGE_INCONCLUSIVE = "TRIAGE_INCONCLUSIVE"


class AttackPathRole(StrEnum):
    ENTRY = "ENTRY"
    LATERAL = "LATERAL"
    FINAL_HOP = "FINAL_HOP"


class PlanStatus(StrEnum):
    PLAN_FOUND = "PLAN_FOUND"
    NO_FEASIBLE_PLAN_WITHIN_K = "NO_FEASIBLE_PLAN_WITHIN_K"
    PLANNING_INCONCLUSIVE = "PLANNING_INCONCLUSIVE"


class NoPlanReason(StrEnum):
    K_EXCEEDED = "K_EXCEEDED"
    UNKNOWN_IMPACT_EXCLUDED = "UNKNOWN_IMPACT_EXCLUDED"
    NO_ELIGIBLE_ACTION = "NO_ELIGIBLE_ACTION"


class PlanningInconclusiveReason(StrEnum):
    SCOPE_INCOMPLETE = "SCOPE_INCOMPLETE"
    CATALOGUE_TOO_LARGE = "CATALOGUE_TOO_LARGE"
    CHAIN_ENUMERATION_TRUNCATED = "CHAIN_ENUMERATION_TRUNCATED"


class PlanOptimality(StrEnum):
    EXACT_WITHIN_K = "EXACT_WITHIN_K"
    NOT_EXACT = "NOT_EXACT"


class ImpactStatus(StrEnum):
    KNOWN_ZERO_DISRUPTION = "KNOWN_ZERO_DISRUPTION"
    KNOWN_DISRUPTION = "KNOWN_DISRUPTION"
    IMPACT_PARTIALLY_UNKNOWN = "IMPACT_PARTIALLY_UNKNOWN"


class DependencyManifest(StrEnum):
    COMPLETE = "COMPLETE"
    PARTIAL = "PARTIAL"
    NONE = "NONE"


class SimulationStatus(StrEnum):
    SIMULATED_CONTAINMENT = "SIMULATED_CONTAINMENT"  # only ever emitted together with a certificate
    SIMULATED_RESIDUAL_EXPOSURE = "SIMULATED_RESIDUAL_EXPOSURE"
    SIMULATION_REJECTED = "SIMULATION_REJECTED"
    SIMULATION_INCONCLUSIVE = "SIMULATION_INCONCLUSIVE"


class CertificateStatus(StrEnum):
    VALID = "VALID"
    EXPIRED = "EXPIRED"
    SUPERSEDED = "SUPERSEDED"
    REVERIFICATION_FAILED = "REVERIFICATION_FAILED"


class SandboxOpResult(StrEnum):
    APPLIED = "APPLIED"
    REJECTED_VALIDATION = "REJECTED_VALIDATION"
    REJECTED_UNAUTHORIZED = "REJECTED_UNAUTHORIZED"
    REJECTED_LIMIT = "REJECTED_LIMIT"
    REJECTED_CONTRADICTS_POLICY = "REJECTED_CONTRADICTS_POLICY"


class GatewayRejection(StrEnum):
    UNAUTHORIZED_ACTION = "UNAUTHORIZED_ACTION"
    STALE_REVISION_REJECTED = "STALE_REVISION_REJECTED"
    MISSING_CERTIFICATE = "MISSING_CERTIFICATE"
    LIVE_MODE_DISABLED = "LIVE_MODE_DISABLED"
