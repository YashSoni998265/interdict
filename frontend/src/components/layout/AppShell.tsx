function NavItem({ to, children, end = false, match }: { to: string; children: string; end?: boolean; match?: boolean }) {
  return (
    <NavLink
      to={to}
      end={end}
      className={({ isActive }) =>
        cn(
          'rounded-md px-2.5 py-1.5 text-ui font-medium transition-colors',
          isActive || match ? 'bg-elevated text-fg' : 'text-fg-muted hover:text-fg',
        )
      }
    >
      {children}
    </NavLink>
  );
}

